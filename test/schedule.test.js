import { describe, it, expect } from "vitest"
import { minIntervalMinutes as m } from "../schedule.js"

describe("minIntervalMinutes", () => {
	it.each([
		["* * * * *", 1],
		["*/5 * * * *", 5],
		["*/15 * * * *", 15],
		["0,10 * * * *", 10],
		["0 * * * *", 60],
		["30 */2 * * *", 120],
		["0 21 * * *", 1440],
		["0 6,18 * * *", 720],
		["0 6,7 * * *", 60],
		["0 23,0 * * *", 60],
		["5-10 3 * * *", 1],
		["0-30/10 3 * * *", 10],
		["5/20 3 * * *", 20],
		["0 21 * * 1", 1440],
		["  0   21  *  *  *  ", 1440],
		["@hourly", 60],
		["@daily", 1440],
		["@weekly", 10080],
	])("%s は %i 分", (expr, minutes) => expect(m(expr)).toBe(minutes))

	it.each([
		"", "   ", undefined, 5,
		"0 21 * *", // 4 フィールド
		"0 0 21 * * *", // 6 フィールド（秒つき）
		"2026-12-31T00:00:00Z", // ISO 日時（ワンショット）
		"@reboot", "@every 5m",
		"60 * * * *", "* 24 * * *", "-1 * * * *", "5-1 * * * *",
		"*/0 * * * *", "a * * * *", "? * * * *", "L * * * *",
	])("解釈できない・範囲外の %j は例外", (expr) => expect(() => m(expr)).toThrow())
})
